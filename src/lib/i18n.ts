export function getString(key: string, lang: Lang): string {
  return strings[lang]?.[key] ?? strings.zh[key] ?? key
}

export function t(key: string, lang: Lang, params?: Record<string, string>): string {
  let s = getString(key, lang)
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(`{${k}}`, v)
    }
  }
  return s
}
